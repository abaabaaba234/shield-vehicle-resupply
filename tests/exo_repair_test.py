"""Real packaged Lua with filediver mech config and guarded native map fixtures.

Engine calls are mocked: tests prove selection/ownership/write behavior, not
that a detached arm model can be regenerated by the game.
"""
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
ns = {'__file__': str(ROOT / 'tests/repair_native_test.py')}
source = (ROOT / 'tests/repair_native_test.py').read_text()
exec(compile(source.split('\nmem, lua, cfg, rec, logs, samples = make()', 1)[0], 'repair-harness', 'exec'), ns)
make, run, Q, U, I, BASE = (ns[k] for k in ('make', 'run', 'Q', 'U', 'I', 'BASE'))
EXO, ARM = 'c2d449ecf7facab1', '32c7063b4bcc4208'
F = lambda n: struct.pack('<f', n)
SM, ENTRIES, ROWS = 0x56000000, 0x56001000, 0x56002000
AM, AENTRIES, AROWS = 0x57000000, 0x57001000, 0x57002000
STATROOT, ATTROOT = BASE + 0x3331000, BASE + 0x3331800


def maps(mem, at, entries, pairs):
    mem.w(at, Q(entries) + U(16) + U(0xffffffff) + U(1))
    mem.w(entries, (U(0xffffffff) * 2) * 16)
    for key, row in pairs:
        slot = key % 16
        while mem.r(entries + slot * 8, 4) != U(0xffffffff):
            slot = (slot + 1) % 16
        mem.w(entries + slot * 8, U(key) + U(row))


def fixture(resource=EXO):
    mem, lua, cfg, rec, logs, samples = make()
    # Replace the harness FRV with the actual filediver EXO-49 config.
    mem.w(0x20000000 + 0xF32F18, Q(int(resource, 16)))
    mem.w(0x40000000, bytes(1002 * 16))
    mem.w(0x40000000 + int(resource, 16) % 1002 * 16, Q(int(resource, 16)) + U(3) + U(0))
    blob = (ROOT / 'tests/fixtures/exo49_health_filediver.bin').read_bytes()
    if resource != EXO:
        # Minimal arm-shaped Health config; the actual upgraded resource is tested in roster.
        blob = bytearray(blob)
        blob[:4] = I(800)
        blob[0x208:] = bytes(len(blob) - 0x208)
        blob[0x208+0x60:0x208+0x64] = U(0x372f0418)
        blob[0x208+0xe8:0x208+0xec] = I(800)
    mem.w(cfg, bytes(blob))
    mem.w(rec, bytes(0x1b8)); mem.w(rec + 0x14, blob[:4])
    for i in range(38):
        zm = struct.unpack_from('<i', blob, 0x208 + i * 0x228 + 0xe8)[0]
        mem.w(rec + 0xf8 + i * 4, I(zm))
    r = lua.eval(b'SVR.R')
    for name in (b'stat', b'attach'):
        sig = r.signatures[name]
        mem.w(BASE + sig[1], bytes(0 if t == '??' else int(t, 16) for t in sig[2].decode().split()))
    sp, ap = BASE + r.signatures[b'stat'][1], BASE + r.signatures[b'attach'][1]
    mem.w(sp + 0xb, I(STATROOT - sp - 0xf))
    mem.w(ap + 0x1d, I(ATTROOT - ap - 0x21))
    mem.w(ap + 0x97, U(0x30)); mem.w(ap + 0x9e, b'\x30')
    mem.w(STATROOT, Q(SM)); maps(mem, SM + 0x20, ENTRIES, [(100, 0)])
    mem.w(SM + 0x48, Q(ROWS)); mem.w(ROWS, F(.75) + F(1) * 12)
    mem.w(ATTROOT, Q(AM)); maps(mem, AM + 0x18, AENTRIES, [])
    mem.w(AM + 0x30, Q(AROWS)); mem.w(AROWS, bytes(0x30))
    r.next_check = 0
    assert r.ensure(2) and r.stats is not None and r.attach is not None
    lua.execute(b'''
      SVR.C.part_repair=false; SVR.C.exo_leg_fix=true
      sim_speed_writes=0
      SVR.W.f32=function(p,old,new)
        if sim_fail_speed then return false end
        if SVR.N.win.read(p,4)~=old then return false end
        local ffi=require('ffi'); pywrite(p,ffi.string(ffi.new('float[1]',new),4))
        sim_speed_writes=sim_speed_writes+1; return true
      end
    ''')
    return mem, lua, cfg, rec, logs


def hp(mem, at):
    return struct.unpack('<i', mem.r(at, 4))[0]


mem, lua, cfg, rec, logs = fixture()
tail = mem.r(ROWS + 4, 48)
run(lua)
assert mem.r(ROWS, 4) == F(1) and mem.r(ROWS + 4, 48) == tail
assert lua.eval(b'sim_speed_writes') == lua.eval(b'SVR.R.legs_fixed') == 1
run(lua)
assert lua.eval(b'sim_speed_writes') == 1
assert 'exo leg repaired' in (logs / 'ShieldVehicleResupply.log').read_text(encoding='utf-8')
print('PASS: fully repaired actual eight-zone EXO config restores only speed; dense row zero works')

for why in ('damaged leg', 'damaged hull', 'destroyed state', 'disabled part', 'disabled fix',
            'non-authority', 'dead', 'no shield', 'cooldown', 'other multiplier', 'missing stat row', 'write failed'):
    mem, lua, cfg, rec, logs = fixture()
    if why == 'damaged leg': mem.w(rec + 0xf8 + 5 * 4, I(549))
    elif why == 'damaged hull': mem.w(rec + 0x14, I(1799))
    elif why == 'destroyed state': mem.w(rec + 0x20, U(2 * 4**5))
    elif why == 'disabled part': lua.execute(b"SVR.C.part['c2d449ecf7facab1:64a3fa1d']=false")
    elif why == 'disabled fix': lua.execute(b'SVR.C.exo_leg_fix=false')
    elif why == 'non-authority': mem.w(0x20000000 + 0xF32F18 + 20, U(0))
    elif why == 'dead': mem.w(rec + 0x19c, U(1))
    elif why == 'no shield': lua.execute(b'SVR.C.test=false')
    elif why == 'cooldown':
        lua.execute(b'SVR.C.exo_leg_fix=false'); run(lua, 10)
        lua.execute(b"SVR.C.exo_leg_fix=true; SVR.C.cooldown=100; SVR.S.last_hit['100:50']=SVR.S.clock")
    elif why == 'other multiplier': mem.w(ROWS, F(.5))
    elif why == 'missing stat row': maps(mem, SM + 0x20, ENTRIES, [])
    elif why == 'write failed': lua.execute(b'sim_fail_speed=true')
    old = mem.r(ROWS, 52)
    run(lua)
    assert mem.r(ROWS, 52) == old and lua.eval(b'sim_speed_writes') == 0, why
print('PASS: damage, death, authority, selection, config, cooldown, range and write failure preserve penalty')

