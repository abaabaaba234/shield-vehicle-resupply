run(lua)
assert mem.r(ROWS,4) == F(1)
print('PASS: colliding entity keys and overflowing hash multiplier locate the correct stat row')

for why in ('stat rows moved', 'config identity moved', 'new damage', 'authority changed'):
    mem, lua, cfg, rec, logs = fixture()
    original_read, injected = mem.r, [False]

    def changing_read(a, n):
        if a == ROWS and n == 4 and not injected[0]:
            injected[0] = True
            if why == 'stat rows moved': mem.w(SM + 0x48, Q(ROWS + 0x1000))
            elif why == 'config identity moved':
                mem.w(0x40000000 + int(EXO,16) % 1002 * 16 + 8, U(5))
            elif why == 'new damage': mem.w(rec + 0xf8 + 5*4, I(100))
            elif why == 'authority changed': mem.w(0x20000000 + 0xF32F18 + 20, U(0))
        return original_read(int(a),int(n))

    lua.globals()[b'pyread'] = changing_read
    run(lua, 6)
    assert lua.eval(b'sim_speed_writes') == 0 and mem.r(ROWS,4) == F(.75), why
print('PASS: moved stat/config rows, new damage and authority changes during a sample prevent speed writes')


def arm_fixture():
    mem, lua, cfg, rec, logs = fixture(ARM)
    # Native attachment chain is explicit, rather than neighbouring IDs or coordinates.
    net, hm, desc = 0x20000000, 0x30000000, 0x20000000 + 0xF32F18
    mem.w(desc + 24, Q(int(EXO, 16)) + U(101) + U(8) + U(51) + U(1))
    maps(mem, net + 0xF1AEB0, 0x21000000, [(100,0),(101,1)])
    maps(mem, net + 0xF22EC8, 0x21001000, [(50,0),(51,1)])
    maps(mem, hm + 0x1030, 0x31000000, [(100,0),(101,1)])
    mem.w(0x31002008, Q(desc + 24))
    mem.w(rec + 0x1b8, bytes(0x1b8)); mem.w(rec + 0x1b8 + 0x14, I(1800))
    parent_cfg = 0x40000000 + 0x3ea0 + 4 * 0x5650
    mem.w(0x40000000 + int(EXO,16) % 1002 * 16, Q(int(EXO,16)) + U(4) + U(0))
    mem.w(parent_cfg, (ROOT / 'tests/fixtures/exo49_health_filediver.bin').read_bytes())
    for i in range(8):
        mem.w(rec + 0x1b8 + 0xf8 + i*4, mem.r(parent_cfg + 0x208 + i*0x228 + 0xe8, 4))
    maps(mem, AM + 0x18, AENTRIES, [(100,0)]); mem.w(AROWS, U(101))
    mem.w(rec + 0x14, I(0)); mem.w(rec + 0xf8, I(0)); mem.w(rec + 0x20, U(2))
    lua.execute(b'SVR.C.part_repair=true; SVR.C.exo_leg_fix=false')

    def game_heal(frac):
        # Simulate only the native call's result, not model rebuilding.
        mem.w(rec + 0x14, I(min(800, hp(mem,rec+0x14) + 100)))
        mem.w(rec + 0xf8, I(min(800, hp(mem,rec+0xf8) + 100)))
        mem.w(rec + 0x20, U(0))

    lua.globals()[b'pyheal'] = game_heal
    return mem, lua, cfg, rec, logs


mem, lua, cfg, rec, logs = arm_fixture()
config_before = mem.r(cfg, 0x1c)
run(lua, 60)
assert lua.eval(b'SVR.S.vehicles[1].kind') == b'arm'
assert hp(mem, rec+0x14) == hp(mem, rec+0xf8) == 800
assert lua.eval(b'sim_calls.heal') == 8, 'repair stopped when destroyed flag cleared but arm was still damaged'
assert mem.r(cfg,0x1c) == config_before, 'native regeneration also enabled beside engine repair'
assert mem.r(ROWS, 4) == F(.75), 'arm modified exosuit movement stat'
print('PASS: upgraded arm discovered; mounted zero-HP arm dispatches game repair until full')

for why in ('engine dead', 'detached', 'dead parent', 'parent non-authority', 'attachment cycle',
            'missing parent', 'bad attach guard', 'disabled arm zone', 'disabled repair', 'no shield'):
    mem, lua, cfg, rec, logs = arm_fixture()
    if why == 'engine dead': mem.w(rec + 0x19c, U(1))
    elif why == 'detached': mem.w(AROWS, U(0))
    elif why == 'dead parent': mem.w(rec + 0x1b8 + 0x14, I(0))
    elif why == 'parent non-authority': mem.w(0x20000000 + 0xF32F18 + 24 + 20, U(0))
    elif why == 'attachment cycle': mem.w(AROWS, U(100))
    elif why == 'missing parent': mem.w(AROWS, U(222))
    elif why == 'bad attach guard':
        r = lua.eval(b'SVR.R'); mem.w(BASE + r.signatures[b'attach'][1], b'\x90'); r.next_check=0; r.ensure(3)
    elif why == 'disabled arm zone': lua.execute(b"SVR.C.part['32c7063b4bcc4208:372f0418']=false")
    elif why == 'disabled repair': lua.execute(b'SVR.C.part_repair=false')
    elif why == 'no shield': lua.execute(b'SVR.C.test=false')
    run(lua)
    assert lua.eval(b'sim_calls.heal') == 0 and hp(mem,rec+0x14) == 0, why
print('PASS: dead/detached arms, invalid parents/guards and disabled repair never receive native calls')

